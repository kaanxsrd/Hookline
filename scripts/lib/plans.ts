/**
 * Reads and validates config/plans.json and renders the generated
 * entitlements modules for Go and TypeScript.
 */

export const LIMIT_KEYS = [
  "endpoints",
  "requests_per_month",
  "retention_hours",
  "max_body_bytes",
  "destinations_per_endpoint",
  "concurrent_tunnels",
  "members",
  "audit_log_days",
  "intake_rate_per_second",
  "intake_burst",
] as const;

export const PLAN_NAMES = ["free", "pro", "team", "anonymous", "unlimited"] as const;

type LimitKey = (typeof LIMIT_KEYS)[number];
type PlanName = (typeof PLAN_NAMES)[number];
type Limits = { name: string } & Record<LimitKey, number | null>;

export type PlansFile = {
  plans: Record<PlanName, Limits>;
  anonymous: { expiry_hours: number; max_requests: number; endpoints_per_ip_per_day: number };
  intake: { per_ip_rate_per_second: number; per_ip_burst: number };
};

const isRecord = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);

const isCount = (v: unknown): v is number => Number.isSafeInteger(v) && (v as number) >= 0;

function exactKeys(obj: Record<string, unknown>, keys: readonly string[], where: string): void {
  const extra = Object.keys(obj).filter((k) => !keys.includes(k));
  const missing = keys.filter((k) => !(k in obj));
  const problems = [
    missing.length ? `missing ${missing.join(", ")}` : "",
    extra.length ? `unknown ${extra.join(", ")}` : "",
  ].filter(Boolean);
  if (problems.length) throw new Error(`${where}: ${problems.join("; ")}`);
}

/** Throws a descriptive error unless raw has exactly the expected shape. */
export function validatePlans(raw: unknown): PlansFile {
  if (!isRecord(raw)) throw new Error("plans.json: expected an object");
  exactKeys(raw, ["plans", "anonymous", "intake"], "plans.json");

  const plans = raw.plans;
  if (!isRecord(plans)) throw new Error("plans: expected an object");
  exactKeys(plans, PLAN_NAMES, "plans");
  for (const name of PLAN_NAMES) {
    const plan = plans[name];
    if (!isRecord(plan)) throw new Error(`plans.${name}: expected an object`);
    exactKeys(plan, ["name", ...LIMIT_KEYS], `plans.${name}`);
    if (typeof plan.name !== "string" || plan.name === "") {
      throw new Error(`plans.${name}.name: expected a non-empty string`);
    }
    for (const key of LIMIT_KEYS) {
      const v = plan[key];
      if (v !== null && !isCount(v)) {
        throw new Error(`plans.${name}.${key}: expected a non-negative integer or null`);
      }
    }
    for (const key of ["retention_hours", "max_body_bytes"] as const) {
      if (plan[key] === null) throw new Error(`plans.${name}.${key}: must not be null`);
    }
  }

  const sections = {
    anonymous: ["expiry_hours", "max_requests", "endpoints_per_ip_per_day"],
    intake: ["per_ip_rate_per_second", "per_ip_burst"],
  } as const;
  for (const [section, keys] of Object.entries(sections)) {
    const value = raw[section];
    if (!isRecord(value)) throw new Error(`${section}: expected an object`);
    exactKeys(value, keys, section);
    for (const key of keys) {
      if (!isCount(value[key]))
        throw new Error(`${section}.${key}: expected a non-negative integer`);
    }
  }
  return raw as PlansFile;
}

const pascal = (s: string) =>
  s
    .split("_")
    .map((p) => (p === "ip" ? "IP" : p.charAt(0).toUpperCase() + p.slice(1)))
    .join("");

const goValue = (v: number | null) => (v === null ? "Unlimited" : String(v));

/** Go source for packages/gocommon/entitlements/plans_gen.go (run gofmt afterwards). */
export function renderGo(p: PlansFile): string {
  const lines = [
    "// Code generated by scripts/gen.ts from config/plans.json. DO NOT EDIT.",
    "",
    "package entitlements",
    "",
    "var plans = map[Plan]Limits{",
  ];
  for (const name of PLAN_NAMES) {
    const plan = p.plans[name];
    lines.push(`\tPlan${pascal(name)}: {`, `\t\tName: ${JSON.stringify(plan.name)},`);
    for (const key of LIMIT_KEYS) lines.push(`\t\t${pascal(key)}: ${goValue(plan[key])},`);
    lines.push("\t},");
  }
  lines.push("}", "", "var anonymousRules = AnonymousRules{");
  for (const [k, v] of Object.entries(p.anonymous)) lines.push(`\t${pascal(k)}: ${v},`);
  lines.push("}", "", "var intakeRules = IntakeRules{");
  for (const [k, v] of Object.entries(p.intake)) lines.push(`\t${pascal(k)}: ${v},`);
  lines.push("}", "");
  return lines.join("\n");
}

/** TypeScript source for packages/shared/src/entitlements.gen.ts (run Biome afterwards). */
export function renderTs(p: PlansFile): string {
  return [
    "// Code generated by scripts/gen.ts from config/plans.json. DO NOT EDIT.",
    "",
    `export const plans = ${JSON.stringify(p.plans, null, 2)} as const;`,
    "",
    `export const anonymousRules = ${JSON.stringify(p.anonymous, null, 2)} as const;`,
    "",
    `export const intakeRules = ${JSON.stringify(p.intake, null, 2)} as const;`,
    "",
  ].join("\n");
}
