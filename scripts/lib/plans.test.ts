import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { renderGo, renderTs, validatePlans } from "./plans";

const raw = JSON.parse(readFileSync(join(import.meta.dir, "../../config/plans.json"), "utf8"));

describe("plans.json", () => {
  test("is valid", () => {
    expect(() => validatePlans(raw)).not.toThrow();
  });

  test("rejects unknown and missing keys and bad values", () => {
    const clone = () => structuredClone(raw);

    const extra = clone();
    extra.plans.free.bananas = 1;
    expect(() => validatePlans(extra)).toThrow(/plans.free: unknown bananas/);

    const missing = clone();
    delete missing.plans.pro.endpoints;
    expect(() => validatePlans(missing)).toThrow(/plans.pro: missing endpoints/);

    const negative = clone();
    negative.plans.team.endpoints = -1;
    expect(() => validatePlans(negative)).toThrow(/plans.team.endpoints/);

    const nullBody = clone();
    nullBody.plans.free.max_body_bytes = null;
    expect(() => validatePlans(nullBody)).toThrow(/must not be null/);
  });

  test("renders Go with Unlimited for null", () => {
    const go = renderGo(validatePlans(raw));
    expect(go).toContain("// Code generated by scripts/gen.ts");
    expect(go).toContain("\tPlanFree: {");
    expect(go).toContain("\t\tMaxBodyBytes: 262144,");
    expect(go).toContain("\t\tMembers: Unlimited,");
    expect(go).toContain("\tEndpointsPerIPPerDay: 5,");
  });

  test("renders TypeScript", () => {
    const ts = renderTs(validatePlans(raw));
    expect(ts).toContain("export const plans = {");
    expect(ts).toContain('"members": null');
  });
});
